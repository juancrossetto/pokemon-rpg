/** Lado mayor del sprite nativo, o `null` si la especie no está en la tabla. */
export function spriteNaturalPx(
  speciesName: string,
  facing: "front" | "back",
): number | null {
  const entry = SPRITE_NATURAL_PX[speciesName.trim().toLowerCase()];
  if (!entry) return null;
  const px = facing === "back" ? entry[1] : entry[0];
  return px > 0 ? px : null;
}
